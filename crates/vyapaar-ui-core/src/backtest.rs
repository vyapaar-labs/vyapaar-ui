//! Backtest results viewer primitives.
//!
//! A thin presentational mapping of a completed backtest run over
//! `vyapaar-runtime-backtest`'s `BacktestResult`: the summary metric card and
//! the equity curve. No domain logic lives here (per
//! `docs/plans/0005-fincept-terminal-screen-inventory.md` §2, the backtest
//! results screen is a view over the runtime crate, not a reimplementation of
//! it). All values are exact `Decimal`s — the same wire fields
//! `BacktestResult` reports.

use rust_decimal::Decimal;
use serde::{Deserialize, Serialize};

use super::atoms::EquityPoint;

/// Lifecycle status of a backtest run as shown on the results screen.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BacktestStatus {
    /// No run has been loaded yet.
    Idle,
    /// A run is in progress.
    Running,
    /// The run finished with a result summary.
    Complete,
    /// The run failed before producing results.
    Failed,
}

/// Summary metrics of one completed backtest run.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BacktestSummary {
    /// Starting cash deployed in the run.
    pub initial_cash: Decimal,
    /// Final equity (settled cash + mark-to-market).
    pub final_equity: Decimal,
    /// Net PnL after statutory costs and fees.
    pub net_pnl: Decimal,
    /// Gross trading PnL before costs.
    pub gross_pnl: Decimal,
    /// Total statutory costs + transaction fees.
    pub total_fees: Decimal,
    /// Total executed trades / fills.
    pub total_trades: u64,
    /// Total candidate signals generated by the strategy.
    pub total_signals: u64,
    /// Orders refused by the pre-trade risk gate.
    pub refused_orders: u64,
    /// Maximum drawdown (positive percentage, e.g. `5.25` for 5.25%).
    pub max_drawdown_pct: Decimal,
    /// Cumulative fill price-impact/slippage.
    pub price_impact: Decimal,
}

impl BacktestSummary {
    /// The zero summary (empty run).
    pub fn zero() -> Self {
        Self {
            initial_cash: Decimal::ZERO,
            final_equity: Decimal::ZERO,
            net_pnl: Decimal::ZERO,
            gross_pnl: Decimal::ZERO,
            total_fees: Decimal::ZERO,
            total_trades: 0,
            total_signals: 0,
            refused_orders: 0,
            max_drawdown_pct: Decimal::ZERO,
            price_impact: Decimal::ZERO,
        }
    }

    /// Total return over the run as a percentage, or zero when initial cash
    /// is zero.
    pub fn total_return_pct(&self) -> Decimal {
        if self.initial_cash.is_zero() {
            return Decimal::ZERO;
        }
        (self.final_equity - self.initial_cash) / self.initial_cash * Decimal::from(100)
    }
}

/// The full presentational state of a backtest results screen.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct BacktestResultView {
    /// Run status.
    pub status: BacktestStatus,
    /// Summary metric card of the last completed run.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub summary: Option<BacktestSummary>,
    /// Mark-to-market equity curve points, in run order.
    pub equity_curve: Vec<EquityPoint>,
}

impl BacktestResultView {
    /// Create an empty, idle results view.
    pub fn empty() -> Self {
        Self {
            status: BacktestStatus::Idle,
            summary: None,
            equity_curve: Vec::new(),
        }
    }

    /// Whether a completed run's results are present.
    pub fn has_results(&self) -> bool {
        self.status == BacktestStatus::Complete && self.summary.is_some()
    }

    /// The last equity point of the curve, if any.
    pub fn last_equity(&self) -> Option<EquityPoint> {
        self.equity_curve.last().copied()
    }

    /// Peak equity across the curve, if any.
    pub fn peak_equity(&self) -> Option<Decimal> {
        self.equity_curve
            .iter()
            .map(|p| p.value)
            .max_by(|a, b| a.cmp(b))
    }

    /// Trough equity across the curve, if any.
    pub fn trough_equity(&self) -> Option<Decimal> {
        self.equity_curve
            .iter()
            .map(|p| p.value)
            .min_by(|a, b| a.cmp(b))
    }
}
